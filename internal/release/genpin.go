package release

import (
	"encoding/json"
	"fmt"
)

// RenderPinnedRoot produces the Go source for pinned.go with a populated trust
// root. Used by the release tool so the pinned keys are generated, never
// hand-edited.
func RenderPinnedRoot(r TrustRoot) ([]byte, error) {
	if err := r.validateShape(); err != nil {
		return nil, err
	}
	compact, err := json.Marshal(r)
	if err != nil {
		return nil, err
	}
	// Pretty form for review; the Go string is the compact JSON.
	pretty, _ := json.MarshalIndent(r, "", "  ")
	src := fmt.Sprintf(`// Copyright (c) 2026 Suryansh Deshwal
// Licensed under the Apache License, Version 2.0

package release

import (
	"encoding/json"
	"fmt"
)

// Code generated by vx6-release pin-root. DO NOT EDIT.
//
// Pinned release trust root (PUBLIC keys and threshold only; no secrets).
// Review before committing:
/*
%s
*/

import (
	"encoding/json"
	"fmt"
)

var pinnedTrustRootJSON = %q

var ErrNoPinnedRoot = fmt.Errorf("no release trust root is pinned in this build; automatic updates are disabled")

func PinnedTrustRoot() (TrustRoot, error) {
	if pinnedTrustRootJSON == "" {
		return TrustRoot{}, ErrNoPinnedRoot
	}
	var r TrustRoot
	if err := json.Unmarshal([]byte(pinnedTrustRootJSON), &r); err != nil {
		return TrustRoot{}, fmt.Errorf("corrupt pinned trust root: %%w", err)
	}
	if err := r.validateShape(); err != nil {
		return TrustRoot{}, fmt.Errorf("invalid pinned trust root: %%w", err)
	}
	return r, nil
}
`, pretty, string(compact))
	return []byte(src), nil
}
